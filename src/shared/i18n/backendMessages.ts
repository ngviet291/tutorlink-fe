/** Message BE có số thay đổi (không đưa vào bảng cố định được). */
const DYNAMIC_PATTERNS: Array<{ re: RegExp; vi: (m: RegExpMatchArray) => string }> = [
  { re: /^At most (\d+) images are allowed$/, vi: (m) => `Tối đa ${m[1]} ảnh` },
  { re: /^Each image must not exceed (\d+)MB$/, vi: (m) => `Mỗi ảnh tối đa ${m[1]}MB` },
  {
    re: /^Invalid value '(.*)' for field '(.*)'\. Accepted values: (.*)$/,
    vi: (m) => `Giá trị '${m[1]}' không hợp lệ cho trường '${m[2]}'. Giá trị cho phép: ${m[3]}`,
  },
  {
    re: /^Invalid enum value for parameter '(.*)': '(.*)'\. Expected one of (.*)\.$/,
    vi: (m) => `Giá trị '${m[2]}' không hợp lệ cho tham số '${m[1]}'. Giá trị cho phép: ${m[3]}`,
  },
];

const VIETNAMESE_RE =
  /[àáạảãâầấậẩẫăằắặẳẵèéẹẻẽêềếệểễìíịỉĩòóọỏõôồốộổỗơờớợởỡùúụủũưừứựửữỳýỵỷỹđ]/i;

export function currentLanguage(): "vi" | "en" {
  return (i18n.language ?? "vi").startsWith("en") ? "en" : "vi";
}

/**
 * Trả message theo ngôn ngữ đang chọn nếu nhận ra được message của BE.
 * - Tiếng Việt: dùng bảng dịch; tiếng Anh: giữ nguyên câu của BE.
 * - Message vốn đã là tiếng Việt (do BE hoặc FE tạo) giữ nguyên.
 * - Không nhận ra: trả undefined để nơi gọi dùng câu chung theo mã lỗi.
 */
export function translateBackendMessage(message: unknown): string | undefined {
  if (typeof message !== "string") return undefined;
  const text = message.trim();
  if (!text) return undefined;
  const lang = currentLanguage();

  const known = BACKEND_MESSAGES_VI[text];
  if (known) return lang === "vi" ? known : text;

  for (const { re, vi } of DYNAMIC_PATTERNS) {
    const m = text.match(re);
    if (m) return lang === "vi" ? vi(m) : text;
  }

  // Message vốn đã là tiếng Việt thì dùng luôn
  if (VIETNAMESE_RE.test(text)) return text;
  return undefined;
}
